"""Generate the Apps Script catalog from the canonical JSON; --check is read-only."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated_catalog() -> str:
    catalog = json.loads((ROOT / 'modules/badge_catalog.json').read_text(encoding='utf-8'))
    return ('// Generated by scripts/sync_badge_catalog.py; edit modules/badge_catalog.json.\n'
            + 'const BADGE_CATALOG = ' + json.dumps(catalog, ensure_ascii=False, indent=2) + ';\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'apps_script/BadgeCatalog.gs'
    expected = generated_catalog()
    if args.check:
        if not destination.exists() or destination.read_text(encoding='utf-8') != expected:
            raise SystemExit('Badge catalog is stale. Run python scripts/sync_badge_catalog.py')
    else:
        destination.write_text(expected, encoding='utf-8')
